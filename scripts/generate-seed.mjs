// Builds supabase/seed.sql from data/program.json.
// Usage: npm run seed:generate
//
// The seed attaches every row to the account owner (public.current_owner()),
// so run it in the Supabase SQL editor only after you've signed up in the app.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const program = JSON.parse(readFileSync(join(root, 'data/program.json'), 'utf8'))

const AREAS = ['lifting', 'jumping', 'running', 'calisthenics', 'mobility', 'accessory', 'movement']
const FEAT_AREAS = ['lifting', 'jumping', 'running', 'calisthenics', 'mobility']
const MEASURES = ['load_reps', 'reps', 'hold', 'distance', 'load_distance', 'contacts', 'duration']
const BLOCKS = ['warmup', 'skill', 'power', 'strength', 'conditioning', 'accessory', 'mobility']
const DAY_TYPES = ['hard', 'easy', 'recovery', 'rest']
const STAGES = ['now', 'next', 'background', 'achieved']

const errors = []
const check = (ok, message) => {
  if (!ok) errors.push(message)
}

// ---- validate ----------------------------------------------------------------

const slugs = new Set()
for (const e of program.exercises) {
  check(!slugs.has(e.slug), `duplicate exercise slug: ${e.slug}`)
  slugs.add(e.slug)
  check(AREAS.includes(e.area), `exercise ${e.slug}: bad area ${e.area}`)
  check(MEASURES.includes(e.measure), `exercise ${e.slug}: bad measure ${e.measure}`)
}

const weekdays = new Set()
for (const slot of program.template) {
  check(slot.weekday >= 1 && slot.weekday <= 7, `bad weekday ${slot.weekday}`)
  check(!weekdays.has(slot.weekday), `duplicate weekday ${slot.weekday}`)
  weekdays.add(slot.weekday)
  check(DAY_TYPES.includes(slot.day_type), `weekday ${slot.weekday}: bad day_type ${slot.day_type}`)
  for (const item of slot.items) {
    check(slugs.has(item.exercise), `weekday ${slot.weekday}: unknown exercise ${item.exercise}`)
    check(BLOCKS.includes(item.block), `weekday ${slot.weekday}: bad block ${item.block}`)
    check(
      item.prescription === 'ladder' || typeof item.prescription === 'object',
      `weekday ${slot.weekday} ${item.exercise}: prescription must be an object or "ladder"`,
    )
  }
}

const featSlugs = new Set()
for (const f of program.feats) {
  check(!featSlugs.has(f.slug), `duplicate feat slug: ${f.slug}`)
  featSlugs.add(f.slug)
  check(FEAT_AREAS.includes(f.area), `feat ${f.slug}: bad area ${f.area}`)
  check(STAGES.includes(f.stage), `feat ${f.slug}: bad stage ${f.stage}`)
  check(f.steps.length > 0, `feat ${f.slug}: needs at least one step`)
  check(f.steps.filter((s) => s.goal).length === 1, `feat ${f.slug}: needs exactly one goal step`)
}

if (errors.length) {
  console.error('data/program.json has problems:\n- ' + errors.join('\n- '))
  process.exit(1)
}

// ---- emit SQL ----------------------------------------------------------------

const lit = (v) => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  return `'${String(v).replaceAll("'", "''")}'`
}
const json = (v) => lit(JSON.stringify(v ?? {}))
const rows = (list) => list.map((r) => `  (${r.join(', ')})`).join(',\n')

const exerciseRows = program.exercises.map((e) => [lit(e.slug), lit(e.name), lit(e.area), lit(e.measure), lit(e.cues)])

const slotRows = program.template.map((s) => [lit(s.weekday), lit(s.name), lit(s.day_type), lit(s.mobility), lit(s.notes)])

const itemRows = program.template.flatMap((s) =>
  s.items.map((item, i) => [
    lit(s.weekday),
    lit(i + 1),
    lit(item.exercise),
    lit(item.block),
    json(item.prescription === 'ladder' ? program.ladder : item.prescription),
    lit(item.notes),
    lit(item.min_week),
    lit(item.max_week),
    lit(item.week_parity),
  ]),
)

const featRows = program.feats.map((f, i) => [
  lit(f.slug),
  lit(f.name),
  lit(f.area),
  lit(f.stage),
  lit(f.target),
  lit(f.unlock),
  lit(f.rough_time),
  lit(f.notes),
  lit(i + 1),
])

const stepRows = program.feats.flatMap((f) =>
  f.steps.map((s, i) => [lit(f.slug), lit(i + 1), lit(s.description), json(s.target), lit(!!s.goal), lit(!!s.bonus)]),
)

const sql = `-- Generated by scripts/generate-seed.mjs from data/program.json. Do not edit by hand.
-- Run once, after you've signed up in the app. Everything is attached to that account.

begin;

do $$
begin
  if public.current_owner() is null then
    raise exception 'No account yet. Sign up in the app first, then run this seed.';
  end if;
  if exists (select 1 from public.template_slots where user_id = public.current_owner()) then
    raise exception 'Seed already applied: the weekly template exists.';
  end if;
end $$;

insert into public.exercises (slug, name, area, measure, cues) values
${rows(exerciseRows)}
on conflict (user_id, slug) do nothing;

insert into public.template_slots (weekday, name, day_type, mobility, notes) values
${rows(slotRows)};

insert into public.template_items
  (slot_id, position, exercise_id, block, prescription, notes, min_week, max_week, week_parity)
select ts.id, v.position, e.id, v.block, v.prescription::jsonb, v.notes,
       v.min_week::smallint, v.max_week::smallint, v.week_parity
from (values
${rows(itemRows)}
) as v(weekday, position, exercise_slug, block, prescription, notes, min_week, max_week, week_parity)
join public.template_slots ts on ts.weekday = v.weekday and ts.user_id = public.current_owner()
join public.exercises e on e.slug = v.exercise_slug and e.user_id = public.current_owner();

insert into public.feats (slug, name, area, stage, target, unlock, rough_time, notes, position) values
${rows(featRows)}
on conflict (user_id, slug) do nothing;

insert into public.feat_steps (feat_id, step_number, description, target, is_goal, is_bonus)
select f.id, v.step_number, v.description, v.target::jsonb, v.is_goal, v.is_bonus
from (values
${rows(stepRows)}
) as v(feat_slug, step_number, description, target, is_goal, is_bonus)
join public.feats f on f.slug = v.feat_slug and f.user_id = public.current_owner();

insert into public.changes (author, summary, reason)
values ('app', 'Seeded exercises, weekly template and feats from data/program.json', 'Initial setup');

commit;
`

writeFileSync(join(root, 'supabase/seed.sql'), sql)
const itemCount = itemRows.length
const stepCount = stepRows.length
console.log(
  `Wrote supabase/seed.sql: ${exerciseRows.length} exercises, ${slotRows.length} template days, ` +
    `${itemCount} template items, ${featRows.length} feats, ${stepCount} ladder steps.`,
)
